export interface BaseSceneObject {
  id: string;
  type: SceneObjectType;
  name?: string;
  /** Members of a generated set (a Table Designer arrangement) share a groupId. */
  groupId?: string | null;
  positionMm: Vec3;
  rotationDeg: Vec3;
  scale: Vec3;
  locked?: boolean;
  hidden?: boolean;
  opacity?: number;
  /**
   * Applied surface finishes, keyed by the part they were dropped on.
   *
   * On `BaseSceneObject` rather than on the catalogue object, because a
   * material has to work on everything in the scene — a wall, a stage deck, a
   * truss, a stand fascia — and putting it anywhere narrower would mean
   * writing the same feature five times. `'*'` covers the whole object; a
   * named key covers one glTF material or one procedural surface, which is
   * what makes dropping onto a specific part behave the way it looks.
   */
  finishes?: FinishMap;
}

/** A placed catalogue model. */
export interface CatalogSceneObject extends BaseSceneObject {
  type: 'catalog';
  catalogItemId: number;
  /** Cached so the scene renders before the catalogue query resolves. */
  modelUrl?: string;
  dimensionsMm?: { width: number; depth: number; height: number };
  /**
   * Seat count and shape, cached from the catalogue for the same reason as
   * the dimensions: the seating chart has to read the layout without a
   * round trip, and a plan opened offline still needs to know what seats.
   */
  seatsDefault?: number | null;
  tableShape?: 'round' | 'rectangular' | 'other' | null;
  /**
   * Set when this placement is a generated venue shell rather than a
   * catalogue item, so applying a new venue can replace the old one and the
   * costing pass can leave the building out of the furniture bill.
   */
  venueId?: number | null;
  /** Per-material colour overrides, keyed by glTF material name. */
  materialColors?: Record<string, string>;
  textureVariationId?: number | null;
  textureTilingEnabled?: boolean;
  textureTileSizeM?: number;
  /** Set on objects generated by Table Designer so they can be re-derived. */
  generatedRole?: 'table' | 'chair' | 'linen' | 'centerpiece' | 'place-setting';
  generatedSlot?: string;
}

