/**
 * The scene document.
 *
 * A plan's contents are one JSON document, loaded and saved whole. Nothing
 * queries across plans for individual objects, so normalising them into rows
 * would cost thousands of writes per save and buy nothing.
 *
 * Every linear value here is an integer number of **millimetres**; every angle
 * is in **degrees**. `SCENE_SCHEMA_VERSION` is written into each document so
 * migrations can be applied on read.
 */

