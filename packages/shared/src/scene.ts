/**
 * A camera position somebody thought worth keeping.
 *
 * Distinct from a walkthrough shot, which is a *move* with a duration and an
 * easing, made to be rendered into a video. A view is a still vantage point —
 * "from the door", "the stage from row four", "the sponsor wall" — and its
 * whole purpose is navigation: a client opening a share link has no idea how to
 * orbit a 3D scene, and handing them five named places to stand is the
 * difference between a plan they understand and one they close.
 *
 * Stored in the document so the designer's choices travel with the plan, and
 * exposed on the share page as a strip of thumbnails at the bottom.
 */
export interface SavedView {
  id: string;
  name: string;
  /** Where the camera stands, and what it looks at. Millimetres, as always. */
  positionMm: Vec3;
  targetMm: Vec3;
  fov: number;
  /** A still captured when the view was saved, so the strip has a thumbnail. */
  thumbnailUrl?: string | null;
  /** One line the client reads before they click. */
  note?: string;
  createdAt: string;
}

