/**
 * Render settings.
 *
 * Two modes, because they answer different questions. Fast is the WebGL
 * viewport and costs nothing, so it is what someone works in. Pro is a
 * cloud raytrace that costs credits and is what goes to a client. Keeping the
 * chosen quality on the document means a re-render months later matches the
 * image that was approved.
 */
export interface SceneRenderSettings {
  /** Named look from `lighting.ts`, applied on top of the environment. */
  look: string;
  /** Overall exposure, so a dark look can be brought up without relighting. */
  exposure: number;
  /** Bloom on emissive surfaces — LED walls, neon lettering. */
  bloom: number;
  /** Haze density; beams are invisible without it. */
  haze: number;
  /** Ambient occlusion contact shadows. Costs frames on weak hardware. */
  contactShadows: boolean;
  /** Export width for a still. 3840 is the "4K render" the brief asks for. */
  exportWidth: number;
  exportHeight: number;
  /** Background treatment behind the room. */
  backdrop: 'environment' | 'studio' | 'transparent' | 'color';
  backdropColor: string;
}

